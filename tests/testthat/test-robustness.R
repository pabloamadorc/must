# The default null model and the figures quoted in ?estimate_interactions and
# the vignette come from the simulation installed in inst/simulations.

robustness_results <- function() {
  path <- system.file("simulations", "null_model_robustness.csv", package = "must")
  if (!nzchar(path)) {
    return(NULL)
  }
  utils::read.csv(path, stringsAsFactors = FALSE)
}

# Mean over the scenarios of each truth, then over the truths with equal weight.
mean_over <- function(results, truths) {
  x <- results[results$truth %in% truths, ]
  by_truth <- tapply(x$rate, list(x$truth, x$null_model), mean)
  colMeans(by_truth[truths, , drop = FALSE])
}

test_that("the installed robustness simulation gives the quoted figures", {
  results <- robustness_results()
  skip_if(is.null(results), "robustness results not installed")
  expect_true(all(results$replicates == 100L) && all(results$n_sim == 1000L))
  false <- mean_over(results, c("AD", "MU", "DO", "SAM", "CA"))
  power <- mean_over(results, c("synergy", "antagonism"))
  models <- c("AD", "MU", "BL", "DO", "SAM", "CA", "consensus")
  expect_equal(round(100 * false[models], 1),
               c(AD = 20.2, MU = 24.1, BL = 24.1, DO = 31.9, SAM = 26.5, CA = 16.0,
                 consensus = 0.6))
  expect_equal(round(100 * power[models], 1),
               c(AD = 58.3, MU = 67.1, BL = 67.1, DO = 60.5, SAM = 37.8, CA = 51.5,
                 consensus = 14.9))
  # Data generated by stress addition look synergistic to the other null models
  sam <- results[results$truth == "SAM" & results$null_model %in% c("AD", "MU", "BL", "DO"), ]
  flagged <- sam$rate * sam$tested * sam$combinations
  expect_gt(sum(sam$share_negative * flagged) / sum(flagged), 0.99)
})

test_that("the pre-registered rule applied to the installed results gives the default", {
  results <- robustness_results()
  skip_if(is.null(results), "robustness results not installed")
  false <- mean_over(results, c("AD", "MU", "DO", "SAM", "CA"))
  power <- mean_over(results, c("synergy", "antagonism"))
  models <- setdiff(names(false), "consensus")
  # Defined in two-level factorials and with at least 80% of the highest power
  candidates <- setdiff(models, "CA")
  candidates <- candidates[power[candidates] >= 0.8 * max(power[models])]
  candidates <- candidates[order(false[candidates], -power[candidates])]
  best <- candidates[[1L]]
  tied <- candidates[abs(false[candidates] - false[[best]]) < 0.01]
  if (length(tied) > 1L) {
    best <- tied[which.max(power[tied])]
  }
  expect_identical(best, eval(formals(estimate_interactions.must_fit)$null_models))
  expect_identical(best, eval(formals(estimate_interactions.default)$null_models))
})
